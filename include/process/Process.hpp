#pragma once

#include <atomic>
#include <cstdint>
#include <mutex>
#include <string>
#include <unordered_map>
#include <vector>

enum class ProcessState { Ready, Running, Finished };

// Represents a single CPU instruction.
struct Instruction {
    enum class Type { Print };
    Type type = Type::Print;
    std::string message = "";
    std::string varName = "";
    bool hasCustomMessage = false;

    Instruction() = default;
    explicit Instruction(Type t) : type(t) {}

    // Factory methods for convenient creation
    static Instruction makePrintDefault() {
        Instruction ins;
        ins.type = Type::Print;
        ins.hasCustomMessage = false;
        return ins;
    }

    static Instruction makePrint(std::string msg) {
        Instruction ins;
        ins.type = Type::Print;
        ins.message = std::move(msg);
        ins.hasCustomMessage = true;
        return ins;
    }

    static Instruction makePrintWithVar(std::string msg, std::string var) {
        Instruction ins;
        ins.type = Type::Print;
        ins.message = std::move(msg);
        ins.varName = std::move(var);
        ins.hasCustomMessage = true;
        return ins;
    }

    static Instruction makePrintVar(std::string var) {
        Instruction ins;
        ins.type = Type::Print;
        ins.varName = std::move(var);
        ins.hasCustomMessage = false;
        return ins;
    }
};

// Represents an in-memory log entry generated by PRINT execution.
struct ProcessLog {
    std::string timestamp;
    uint32_t core = 0;
    std::string message;

    std::string format() const {
        return "(" + timestamp + ") Core:" + std::to_string(core) + " \"" + message + "\"";
    }
};

// Thread-safety:
// - executeNext() and executePrint() are executed by the worker core thread owning the process.
// - executedInstructions(), isFinished(), isAttached(), state(), core() are atomic.
// - Logs and symbol table are guarded by mutexes for thread-safe access from the UI/screen thread.
class Process {
public:
    Process(uint32_t id, std::string name, uint32_t instructionCount);
    Process(uint32_t id, std::string name, std::vector<Instruction> instructions);

    uint32_t id() const { return id_; }
    const std::string& name() const { return name_; }
    const std::string& createdAt() const { return createdAt_; }
    uint32_t totalInstructions() const { return static_cast<uint32_t>(instructions_.size()); }
    uint32_t executedInstructions() const { return executed_.load(); }
    bool isFinished() const { return executed_.load() >= totalInstructions(); }

    ProcessState state() const { return state_.load(); }
    void setState(ProcessState s) { state_.store(s); }
    int core() const { return core_.load(); }

    // Screen attachment tracking
    bool isAttached() const { return isAttached_.load(); }
    void setAttached(bool attached) { isAttached_.store(attached); }

    // Scheduler-mutex guarded.
    void markRunning(int core);
    const std::string& startedAt() const { return startedAt_; }

    // Symbol table operations (uint16_t, auto-declares 0 for undeclared variables)
    uint16_t getVariable(const std::string& varName);
    void setVariable(const std::string& varName, uint16_t value);
    bool hasVariable(const std::string& varName) const;
    std::unordered_map<std::string, uint16_t> getSymbolTableSnapshot() const;

    // In-memory log accessors
    std::vector<ProcessLog> getLogs() const;
    std::vector<std::string> getFormattedLogs() const;
    std::vector<std::string> getFormattedLogsSince(size_t index) const;
    size_t getLogCount() const;

    // Runs one CPU tick of work on `core`
    void executeNext(uint32_t core, uint64_t delayPerExec);

private:
    void executePrint(uint32_t core);

    uint32_t id_;
    std::string name_;
    std::string createdAt_;
    std::string startedAt_;
    std::vector<Instruction> instructions_;

    std::atomic<uint32_t> executed_{0};
    std::atomic<ProcessState> state_{ProcessState::Ready};
    std::atomic<int> core_{-1};
    std::atomic<bool> isAttached_{false};
    uint64_t delayRemaining_ = 0;

    // In-memory log buffer
    mutable std::mutex logMtx_;
    std::vector<ProcessLog> logs_;

    // Symbol table (uint16_t variables)
    mutable std::mutex symbolMtx_;
    std::unordered_map<std::string, uint16_t> symbolTable_;
};